def copy_for(language: str) -> dict[str, str]:
    return COPY.get(language, COPY["en"])


def capability_label(capability: str, language: str) -> str:
    copy = copy_for(language)
    return copy.get(f"cap_{capability}", capability.replace("_", " "))


def flag_label(flag: str, language: str) -> str:
    labels = FLAG_LABELS.get(flag, {})
    return labels.get(language, labels.get("en", flag.replace("_", " ")))


def resolve_response_language(requested: Language, detected: str) -> str:
    if requested != Language.AUTO:
        return requested.value
    return detected if detected in {"en", "hi", "kn"} else "en"
